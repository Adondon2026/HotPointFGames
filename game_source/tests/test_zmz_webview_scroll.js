/* WebView-specific nested-scroll regression. Runs on Node without Android. */
'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const read=p=>fs.readFileSync(__dirname+'/../'+p,'utf8');
const html=read('web/90_shell_after_games.html'),css=read('web/lite.css');
const game=read('web/games/siege.html'),build=read('build.py');
const native=fs.readFileSync(__dirname+'/../../app/src/main/java/com/chuanmahjong/nearby/GameActivity.kt','utf8');
const home=fs.readFileSync(__dirname+'/../../app/src/main/java/com/chuanmahjong/nearby/MainActivity.kt','utf8');
assert(html.includes('id="siegeBuffChoices"')&&html.includes('id="siegeBuffBack"'));
assert(css.includes('#siegeAllowedConfig[open] #siegeBuffChoices{max-height:'));
assert(css.includes('overscroll-behavior:contain'));
assert(css.includes('.zmz-webview #settingsModal #siegeAllowedConfig[open] #siegeBuffChoices{touch-action:none}'));
assert(native.includes('onPageFinished')&&native.includes("classList.add('zmz-webview')"));
assert(home.includes('在浏览器打开游戏（兼容模式）')&&home.includes('Intent.ACTION_VIEW'));
assert(build.includes('read("web/games/siege_catalog.js")')&&build.includes('read("web/zmz_scroll.js")'));
assert(game.includes('siegeCatalog'),'must retain upstream v24 gameplay');

let webview=true,open=true,visible=true,sheetScroll=105,listScroll=0,top=230;
const handlers=new Map;
const node=(id,extra={})=>({addEventListener:(name,fn,opts)=>{handlers.set(id+':'+name,{fn,opts})},...extra});
const grid=node('grid',{get scrollTop(){return listScroll},set scrollTop(v){listScroll=Math.max(0,Math.min(650,v))},scrollHeight:900,clientHeight:250});
const details=node('details',{get open(){return open},set open(v){open=v},getBoundingClientRect:()=>({top})});
const sheet={get scrollTop(){return sheetScroll},set scrollTop(v){sheetScroll=v},getBoundingClientRect:()=>({top:120})};
const modal=node('modal',{classList:{contains:k=>k==='hidden'?!visible:false},querySelector:()=>sheet});
const back=node('back');
const elements={settingsModal:modal,siegeAllowedConfig:details,siegeBuffChoices:grid,siegeBuffBack:back};
const document={documentElement:{classList:{contains:()=>webview}},getElementById:id=>elements[id]};
const code=read('web/zmz_scroll.js');
vm.runInNewContext(code,{document},{filename:'zmz_scroll.js'});
const ev=(y,x=55)=>({touches:[{clientY:y,clientX:x}],cancelable:true,prevented:false,stopped:false,
  preventDefault(){this.prevented=true},stopPropagation(){this.stopped=true}});
const fire=(name,e)=>{let h=handlers.get('grid:'+name);assert(h);h.fn(e);return e};
assert.equal(handlers.get('grid:touchmove').opts.passive,false);
fire('touchstart',ev(250));
const move=fire('touchmove',ev(196));
assert(move.prevented&&move.stopped,'WebView must consume inner-list vertical scroll');
assert.equal(listScroll,54);
assert.equal(sheetScroll,105,'Parent settings sheet must not move during list scrolling');
fire('touchmove',ev(80));
assert(listScroll>54);
listScroll=650;const edge=fire('touchmove',ev(40));
assert(edge.prevented&&edge.stopped&&listScroll===650,'No overscroll chaining at list end');
fire('touchend',{});
webview=false;listScroll=0;fire('touchstart',ev(250));
const normal=fire('touchmove',ev(195));
assert(!normal.prevented&&listScroll===0,'Browser native scrolling remains untouched');
webview=true;open=false;fire('touchstart',ev(240));const collapsed=fire('touchmove',ev(150));
assert(!collapsed.prevented);
open=true;handlers.get('back:click').fn();
assert(!open,'Return button must collapse the inner settings');
assert(sheetScroll>=0);
new vm.Script(code,{filename:'zmz_scroll_syntax.js'});
console.log('ZMZ 0.24.1 WebView nested-touch isolation, edge capture, browser fallback and return PASS');
